#!/bin/sh
# Render Traefik's dynamic config from environment variables, then launch both
# processes in one container:
#   - whoami runs in the background on an internal port
#   - Traefik runs in the foreground (via exec) so it becomes PID 1 and
#     receives SIGTERM/SIGINT directly for clean container shutdown.
#
# Traefik's file provider does NOT expand env vars, so we generate the dynamic
# config here at startup and write it into the watched directory.
set -eu

# --- whoami ------------------------------------------------------------------
WHOAMI_PORT="${WHOAMI_PORT:-8000}"
WHOAMI_NAME="${WHOAMI_NAME:-whoami}"

# --- OIDC knobs (with demo-friendly defaults) --------------------------------
OIDC_ENABLED="${OIDC_ENABLED:-true}"
OIDC_CALLBACK_URL="${OIDC_CALLBACK_URL:-/oauth2/callback}"
OIDC_LOGOUT_URL="${OIDC_LOGOUT_URL:-/oauth2/logout}"
# Local demo runs over plain http://, so redirects must NOT be forced to https.
OIDC_FORCE_HTTPS="${OIDC_FORCE_HTTPS:-true}"
OIDC_LOG_LEVEL="${OIDC_LOG_LEVEL:-info}"
OIDC_SCOPES="${OIDC_SCOPES:-openid,profile,email}"
OIDC_EXCLUDED_URLS="${OIDC_EXCLUDED_URLS:-}"

DYNAMIC_DIR="/etc/traefik/dynamic"
DYNAMIC_FILE="${DYNAMIC_DIR}/dynamic.yml"
mkdir -p "${DYNAMIC_DIR}"

# Turn a comma-separated list ("a,b,c") into an inline YAML flow sequence
# ("[\"a\", \"b\", \"c\"]").
to_yaml_list() {
  _out=""
  _oldifs="$IFS"; IFS=","
  for _item in $1; do
    _item="$(printf '%s' "$_item" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
    [ -z "$_item" ] && continue
    if [ -z "$_out" ]; then _out="\"$_item\""; else _out="$_out, \"$_item\""; fi
  done
  IFS="$_oldifs"
  printf '[%s]' "$_out"
}

# --- Render the dynamic config ----------------------------------------------
if [ "${OIDC_ENABLED}" = "true" ]; then
  # Fail fast with a clear message if required inputs are missing.
  : "${REEF_ISSUER:?OIDC_ENABLED=true but REEF_ISSUER is not set (OIDC issuer URL)}"
  : "${REEF_CLIENT_ID:?OIDC_ENABLED=true but REEF_CLIENT_ID is not set}"
  : "${REEF_CLIENT_SECRET:?OIDC_ENABLED=true but REEF_CLIENT_SECRET is not set}"

  # A 32+ byte key encrypts the session cookie. It MUST stay stable across
  # restarts: if it changes, cookies from a previous run can no longer be
  # decoded and the plugin returns "Critical session error" (HTTP 500) until
  # those cookies are cleared. So when no key is provided we generate one once
  # and persist it to a volume, reusing it on subsequent starts.
  if [ -z "${OIDC_SESSION_ENCRYPTION_KEY:-}" ]; then
    _key_file="${OIDC_SESSION_KEY_FILE:-/var/lib/traefikoidc/session.key}"
    if [ -s "${_key_file}" ]; then
      OIDC_SESSION_ENCRYPTION_KEY="$(cat "${_key_file}")"
      echo "entrypoint: reusing persisted session key from ${_key_file}." >&2
    else
      OIDC_SESSION_ENCRYPTION_KEY="$(head -c 48 /dev/urandom | base64 | tr -d '\n')"
      if mkdir -p "$(dirname "${_key_file}")" 2>/dev/null && printf '%s' "${OIDC_SESSION_ENCRYPTION_KEY}" > "${_key_file}" 2>/dev/null; then
        echo "entrypoint: generated a session key and persisted it to ${_key_file}." >&2
      else
        echo "entrypoint: WARNING generated an EPHEMERAL session key (could not persist to ${_key_file}); it will rotate on restart and invalidate existing cookies. Set OIDC_SESSION_ENCRYPTION_KEY to avoid this." >&2
      fi
    fi
  fi

  scopes_yaml="$(to_yaml_list "${OIDC_SCOPES}")"

  echo "entrypoint: rendering dynamic config WITH OIDC auth (issuer=${REEF_ISSUER})." >&2
  cat > "${DYNAMIC_FILE}" <<EOF
# Generated by entrypoint.sh at container startup — do not edit in place.
# Adjust behaviour via environment variables (see .env.example / README).
http:
  routers:
    whoami:
      rule: "PathPrefix(\`/\`)"
      entryPoints:
        - web
      service: whoami
      middlewares:
        - oidc-auth

  services:
    whoami:
      loadBalancer:
        servers:
          - url: "http://127.0.0.1:${WHOAMI_PORT}"

  middlewares:
    oidc-auth:
      plugin:
        traefikoidc:
          providerURL: "${REEF_ISSUER}"
          clientID: "${REEF_CLIENT_ID}"
          clientSecret: "${REEF_CLIENT_SECRET}"
          sessionEncryptionKey: "${OIDC_SESSION_ENCRYPTION_KEY}"
          callbackURL: "${OIDC_CALLBACK_URL}"
          logoutURL: "${OIDC_LOGOUT_URL}"
          forceHTTPS: ${OIDC_FORCE_HTTPS}
          logLevel: "${OIDC_LOG_LEVEL}"
          scopes: ${scopes_yaml}
          enablePKCE: true
EOF
  if [ -n "${OIDC_EXCLUDED_URLS}" ]; then
    printf '          excludedURLs: %s\n' "$(to_yaml_list "${OIDC_EXCLUDED_URLS}")" >> "${DYNAMIC_FILE}"
  fi
else
  echo "entrypoint: rendering dynamic config WITHOUT auth (OIDC_ENABLED=${OIDC_ENABLED})." >&2
  cat > "${DYNAMIC_FILE}" <<EOF
# Generated by entrypoint.sh at container startup — do not edit in place.
http:
  routers:
    whoami:
      rule: "PathPrefix(\`/\`)"
      entryPoints:
        - web
      service: whoami

  services:
    whoami:
      loadBalancer:
        servers:
          - url: "http://127.0.0.1:${WHOAMI_PORT}"
EOF
fi

# --- Launch ------------------------------------------------------------------
whoami --port "${WHOAMI_PORT}" --name "${WHOAMI_NAME}" &

exec traefik --configFile=/etc/traefik/traefik.yml
